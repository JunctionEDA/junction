// gen-cad-script-assets.mjs — what custom features (web/domains/mechanical/script) carry as text, written out as
// modules so that the page, the worker, the assistant's host and the node tests bundle them without a loader
// flag (gen-cad-registry.mjs runs this; the outputs are not committed):
//
//   generated/script-assets.ts   the Feature API's types (script/assets/feature-api.d.ts), the sandbox prelude,
//                                the exemplar scripts (script/assets/exemplars/*.js) and the assistant's
//                                instructions (script/assets/prompts/*.md)
//   generated/script-wasm.ts     the QuickJS interpreter scripts run in (npm @jitl/quickjs-wasmfile-release-sync,
//                                MIT), as base64: about 0.5 MB, in the worker and the host only
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mech = path.resolve(here, "..", "web", "domains", "mechanical");
const assets = path.join(mech, "script", "assets");
const read = (...p) => fs.readFileSync(path.join(assets, ...p), "utf8");
const list = (dir, ext) => (fs.existsSync(path.join(assets, dir)) ? fs.readdirSync(path.join(assets, dir)).filter((f) => f.endsWith(ext)).sort() : []);
const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text); };

const exemplars = list("exemplars", ".js").map((f) => ({ id: f.replace(/\.js$/, ""), source: read("exemplars", f) }));
const prompts = Object.fromEntries(list("prompts", ".md").map((f) => [f.replace(/\.md$/, ""), read("prompts", f)]));
write(path.join(mech, "generated", "script-assets.ts"),
  "// GENERATED by scripts/gen-cad-script-assets.mjs from web/domains/mechanical/script/assets. Do not edit, do not commit.\n" +
  `export const API_DTS: string = ${JSON.stringify(read("feature-api.d.ts"))};\n` +
  `export const PRELUDE: string = ${JSON.stringify(read("prelude.js"))};\n` +
  `export const EXEMPLARS: readonly { id: string; source: string }[] = ${JSON.stringify(exemplars)};\n` +
  `export const PROMPTS: { readonly [name: string]: string } = ${JSON.stringify(prompts)};\n`);

const wasm = path.resolve(here, "..", "node_modules", "@jitl", "quickjs-wasmfile-release-sync", "dist", "emscripten-module.wasm");
write(path.join(mech, "generated", "script-wasm.ts"),
  "// GENERATED by scripts/gen-cad-script-assets.mjs from @jitl/quickjs-wasmfile-release-sync. Do not edit, do not commit.\n" +
  `export default "${fs.readFileSync(wasm).toString("base64")}";\n`);

// docs/WRITING_CUSTOM_FEATURES.md is the guide itself (the page people read is the text the assistant reads).
// It is written here, where the repository's docs folder is at hand (not in the server's container build).
{
  const docs = path.resolve(here, "..", "..", "docs");
  if (fs.existsSync(docs) && prompts.guide) {
    write(path.join(docs, "WRITING_CUSTOM_FEATURES.md"),
      "<!-- Written by server/scripts/gen-cad-script-assets.mjs from server/web/domains/mechanical/script/assets/prompts/guide.md. Edit that file. -->\n\n" + prompts.guide);
  }
}
