// gen-sketch-font.mjs — the glyph outlines sketch text is drawn and built with, read out of the font files in
// server/vendor/fonts (Source Sans Pro, copied from thirdparty/libwmf/fonts, SIL Open Font License 1.1) for the printable Latin-1 characters.
// Written to web/domains/mechanical/generated/sketch-font.ts, which is not committed (gen-cad-registry.mjs runs
// this).  The page and the geometry worker both import it: text has to be the same shape in the sketcher and in
// the solid it is extruded into.
//
// Each glyph is its advance and its outline as a path string in font units, y up:
//   "M x y", "L x y", "Q x1 y1 x y", "C x1 y1 x2 y2 x y", "Z".
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const fonts = path.resolve(here, "..", "vendor", "fonts");
const out = path.resolve(here, "..", "web", "domains", "mechanical", "generated", "sketch-font.ts");

const FACES = { "Source Sans": "SourceSansPro-Regular.ttf", "Source Sans Bold": "SourceSansPro-Semibold.ttf" };
const faces = {};
for (const [name, file] of Object.entries(FACES)) {
  const f = opentype.parse(new Uint8Array(fs.readFileSync(path.join(fonts, file))).buffer);
  const glyphs = {};
  const r = (v) => Math.round(v);
  for (let c = 32; c < 256; c++) {
    if (c >= 127 && c < 160) continue;
    const ch = String.fromCharCode(c), g = f.charToGlyph(ch);
    if (!g || (g.index === 0 && c !== 32)) continue;
    let s = "";
    for (const k of g.getPath(0, 0, f.unitsPerEm).commands) {
      if (k.type === "Z") s += "Z";
      else if (k.type === "M" || k.type === "L") s += `${k.type}${r(k.x)} ${-r(k.y)}`;
      else if (k.type === "Q") s += `Q${r(k.x1)} ${-r(k.y1)} ${r(k.x)} ${-r(k.y)}`;
      else if (k.type === "C") s += `C${r(k.x1)} ${-r(k.y1)} ${r(k.x2)} ${-r(k.y2)} ${r(k.x)} ${-r(k.y)}`;
    }
    glyphs[ch] = [r(g.advanceWidth || 0), s];
  }
  const capHeight = (f.tables.os2 && f.tables.os2.sCapHeight) || r(f.ascender * 0.7);
  faces[name] = { em: f.unitsPerEm, ascent: f.ascender, descent: f.descender, capHeight, glyphs };
}
const text = "// GENERATED by scripts/gen-sketch-font.mjs from vendor/fonts (SIL OFL 1.1). Do not edit, do not commit.\n" +
  "export interface SketchFontFace { em: number; ascent: number; descent: number; capHeight: number; glyphs: { [ch: string]: [number, string] } }\n" +
  `export const SKETCH_FONTS: { [name: string]: SketchFontFace } = ${JSON.stringify(faces)};\n`;
fs.mkdirSync(path.dirname(out), { recursive: true });
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) fs.writeFileSync(out, text);
